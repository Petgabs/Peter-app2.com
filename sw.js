/* Student Report Studio — offline app shell.
   Strategy: navigations are network-first (teachers always get the newest
   index.html when online, and the cached shell when offline); static files
   (images, the on-demand PDF bundle) are cache-first. Report data is never
   handled here — it lives in localStorage / the school cloud. */
const CACHE = 'report-studio-shell-v1';
const SHELL = ['./', 'index.html', 'assets/emblem.png', 'assets/school-name.png', 'assets/watermark.png', 'vendor/pdf-libs.js'];

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // cloud APIs: always live

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then(res => {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put('index.html', copy));
          return res;
        })
        .catch(() => caches.match('index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(hit => hit || fetch(req).then(res => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(req, copy));
      }
      return res;
    }))
  );
});
